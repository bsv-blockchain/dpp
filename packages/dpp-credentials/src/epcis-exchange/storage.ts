/**
 * The storage an EPCIS exchange runs on, and the in-memory adapter.
 *
 * The exchange (exchange.ts) never opens a database. It is handed an object
 * with the six methods below and builds everything else on them: the exact
 * bytes of a source under their digest, and small JSON records under a kind
 * and a key, written in batches that apply completely or not at all.
 *
 * The interface is a set of promises an adapter makes, and the type alone
 * cannot check them. An adapter that does not apply a batch atomically, or
 * that answers before a write is durable, still compiles. That is why the
 * shared adapter suite (adapter-suite.ts) exists: an adapter is fit only when
 * it passes that suite, whatever database is behind it.
 */
import { createHash } from 'node:crypto';
import type { JsonObject } from '../types.js';

/* ---------------------------------- shape -------------------------------- */

/** One stored record: its kind, its key, how many times it has been written, and its value. */
export interface EpcisStoredRecord {
  kind: string;
  key: string;
  /** 1 for the first write, one more for each later write. A batch names it to refuse a stale update. */
  revision: number;
  value: JsonObject;
}

/** `absent` requires that no record is held under the key; a number requires exactly that revision. */
export type EpcisWriteExpectation = 'absent' | number;

export type EpcisStorageWrite =
  | { op: 'put'; kind: string; key: string; value: JsonObject; expect?: EpcisWriteExpectation }
  | { op: 'delete'; kind: string; key: string; expect?: number };

export type EpcisCommitResult =
  | { committed: true }
  | { committed: false; failed: { kind: string; key: string; expected: EpcisWriteExpectation; found: EpcisWriteExpectation } };

export interface EpcisListOptions {
  /** Only keys that start with this text. */
  prefix?: string;
  /** Only keys greater than this one, so a caller pages by passing the last key it saw. */
  after?: string;
  /** At most this many records. */
  limit: number;
}

/**
 * What an adapter promises.
 *
 * 1. `putBytes` resolves only when the bytes are durable under their SHA-256.
 *    Putting bytes already held is a no-op. Bytes whose digest is not the
 *    name are refused.
 * 2. `getBytes` answers exactly the bytes that were put, or undefined. It
 *    never answers part of them.
 * 3. `deleteBytes` removes them and is a no-op when nothing is held.
 * 4. `commit` checks every `expect` first. If one fails, nothing is written
 *    and the answer names it. Otherwise every write of the batch is applied,
 *    and the call resolves only when all of them are durable. After a crash
 *    at any moment inside `commit`, a reopened store holds the whole batch or
 *    none of it.
 * 5. `get` and `list` see committed state only. `list` answers in ascending
 *    key order, compared by UTF-16 code unit.
 * 6. A `put` without `expect` overwrites. A `delete` of an absent key is a
 *    no-op.
 *
 * Kinds and keys are generated by the exchange and are safe as file names:
 * see EPCIS_STORAGE_KIND and EPCIS_STORAGE_KEY. A later feature adds its
 * records under a new kind and needs no new method.
 */
export interface EpcisExchangeStorage {
  putBytes(sha256: string, bytes: Uint8Array): Promise<void>;
  getBytes(sha256: string): Promise<Uint8Array | undefined>;
  deleteBytes(sha256: string): Promise<void>;
  get(kind: string, key: string): Promise<EpcisStoredRecord | undefined>;
  list(kind: string, options: EpcisListOptions): Promise<EpcisStoredRecord[]>;
  commit(writes: readonly EpcisStorageWrite[]): Promise<EpcisCommitResult>;
}

/** A kind is a short lower-case name. */
export const EPCIS_STORAGE_KIND = /^[a-z][a-z0-9-]{0,31}$/;
/** A key is 4 to 200 characters of lower-case letters, digits, dot, underscore and hyphen, starting with a letter or digit. Lower case only, so it is one name on a file system that ignores case. */
export const EPCIS_STORAGE_KEY = /^[0-9a-z][0-9a-z._-]{3,199}$/;
const SHA256 = /^[0-9a-f]{64}$/;

export type EpcisStorageErrorCode = 'invalid-kind' | 'invalid-key' | 'invalid-digest' | 'digest-mismatch' | 'invalid-value' | 'invalid-limit' | 'duplicate-write' | 'locked' | 'corrupt' | 'closed';

/** A call the storage refuses because it is malformed, or a store that cannot be used. Never a failed expectation, which `commit` answers as a value. */
export class EpcisStorageError extends Error {
  readonly code: EpcisStorageErrorCode;
  constructor(code: EpcisStorageErrorCode, message: string) {
    super(message);
    this.name = 'EpcisStorageError';
    this.code = code;
  }
}

export const sha256Hex = (bytes: Uint8Array | string): string => createHash('sha256').update(bytes).digest('hex');

/** The checks every adapter makes before it touches anything, so a malformed call fails the same way everywhere. */
export function assertStorageName(kind: string, key?: string): void {
  if (typeof kind !== 'string' || !EPCIS_STORAGE_KIND.test(kind)) throw new EpcisStorageError('invalid-kind', `a storage kind is a lower-case name of at most 32 characters, not ${JSON.stringify(kind)}`);
  if (key !== undefined && (typeof key !== 'string' || !EPCIS_STORAGE_KEY.test(key))) throw new EpcisStorageError('invalid-key', `a storage key is 4 to 200 characters of [0-9a-z._-], not ${JSON.stringify(key)}`);
}

export function assertStorageDigest(sha256: string): void {
  if (typeof sha256 !== 'string' || !SHA256.test(sha256)) throw new EpcisStorageError('invalid-digest', 'bytes are held under 64 lower-case hex characters of SHA-256');
}

export function assertStorageBytes(sha256: string, bytes: Uint8Array): void {
  assertStorageDigest(sha256);
  if (!(bytes instanceof Uint8Array)) throw new EpcisStorageError('invalid-value', 'bytes are a Uint8Array');
  if (sha256Hex(bytes) !== sha256) throw new EpcisStorageError('digest-mismatch', 'the bytes do not have the digest they are being stored under');
}

export function assertStorageList(kind: string, options: EpcisListOptions): void {
  assertStorageName(kind);
  if (!Number.isSafeInteger(options.limit) || options.limit <= 0) throw new EpcisStorageError('invalid-limit', 'a list names a positive limit');
}

/** Validate a batch and return it with each value copied, so a later change by the caller cannot reach the store. */
export function checkedWrites(writes: readonly EpcisStorageWrite[]): EpcisStorageWrite[] {
  const seen = new Set<string>();
  return writes.map((write) => {
    assertStorageName(write.kind, write.key);
    const name = `${write.kind}\n${write.key}`;
    if (seen.has(name)) throw new EpcisStorageError('duplicate-write', `a batch writes ${write.kind}/${write.key} twice`);
    seen.add(name);
    if (write.expect !== undefined && write.expect !== 'absent' && !(Number.isSafeInteger(write.expect) && write.expect > 0)) throw new EpcisStorageError('invalid-value', 'an expectation is absent or a positive revision');
    if (write.op === 'delete') {
      if ((write.expect as unknown) === 'absent') throw new EpcisStorageError('invalid-value', 'a delete cannot expect the record to be absent');
      return write.expect === undefined ? { op: 'delete', kind: write.kind, key: write.key } : { op: 'delete', kind: write.kind, key: write.key, expect: write.expect };
    }
    if (write.op !== 'put') throw new EpcisStorageError('invalid-value', 'a write is a put or a delete');
    if (write.value == null || typeof write.value !== 'object' || Array.isArray(write.value)) throw new EpcisStorageError('invalid-value', `the value of ${write.kind}/${write.key} is a JSON object`);
    // A JSON round trip is the copy: it also refuses anything JSON cannot carry before a byte is written.
    const value = JSON.parse(JSON.stringify(write.value)) as JsonObject;
    return write.expect === undefined ? { op: 'put', kind: write.kind, key: write.key, value } : { op: 'put', kind: write.kind, key: write.key, value, expect: write.expect };
  });
}

/* --------------------------------- memory -------------------------------- */

/** Everything an in-memory store holds. A second adapter over the same state stands for a restart in a test. */
export interface MemoryEpcisState {
  bytes: Map<string, Uint8Array>;
  records: Map<string, Map<string, { revision: number; value: JsonObject }>>;
}

export function createMemoryEpcisState(): MemoryEpcisState {
  return { bytes: new Map(), records: new Map() };
}

export interface MemoryEpcisStorage extends EpcisExchangeStorage {
  readonly state: MemoryEpcisState;
}

/**
 * The in-memory adapter. It keeps the promises above within one process and
 * loses everything when the process ends, so it suits tests and trials, not
 * a deployment that must survive a restart.
 */
export function createMemoryEpcisStorage(state: MemoryEpcisState = createMemoryEpcisState()): MemoryEpcisStorage {
  const table = (kind: string): Map<string, { revision: number; value: JsonObject }> => {
    let held = state.records.get(kind);
    if (held == null) { held = new Map(); state.records.set(kind, held); }
    return held;
  };
  const found = (kind: string, key: string): EpcisWriteExpectation => state.records.get(kind)?.get(key)?.revision ?? 'absent';
  return {
    state,
    async putBytes(sha256, bytes) {
      assertStorageBytes(sha256, bytes);
      if (!state.bytes.has(sha256)) state.bytes.set(sha256, new Uint8Array(bytes));
    },
    async getBytes(sha256) {
      assertStorageDigest(sha256);
      const held = state.bytes.get(sha256);
      return held == null ? undefined : new Uint8Array(held);
    },
    async deleteBytes(sha256) {
      assertStorageDigest(sha256);
      state.bytes.delete(sha256);
    },
    async get(kind, key) {
      assertStorageName(kind, key);
      const held = state.records.get(kind)?.get(key);
      return held == null ? undefined : { kind, key, revision: held.revision, value: structuredClone(held.value) };
    },
    async list(kind, options) {
      assertStorageList(kind, options);
      const prefix = options.prefix ?? '';
      const keys = [...(state.records.get(kind)?.keys() ?? [])].filter((key) => key.startsWith(prefix) && (options.after == null || key > options.after)).sort();
      return keys.slice(0, options.limit).map((key) => {
        const held = state.records.get(kind)!.get(key)!;
        return { kind, key, revision: held.revision, value: structuredClone(held.value) };
      });
    },
    async commit(writes) {
      const batch = checkedWrites(writes);
      for (const write of batch) {
        if (write.expect === undefined) continue;
        const now = found(write.kind, write.key);
        if (now !== write.expect) return { committed: false, failed: { kind: write.kind, key: write.key, expected: write.expect, found: now } };
      }
      // Nothing between the checks and the last write can yield, so the batch is one step.
      for (const write of batch) {
        if (write.op === 'delete') { state.records.get(write.kind)?.delete(write.key); continue; }
        const held = table(write.kind).get(write.key);
        table(write.kind).set(write.key, { revision: (held?.revision ?? 0) + 1, value: write.value });
      }
      return { committed: true };
    },
  };
}

/* ----------------------------- fault injection --------------------------- */

/** Thrown where a crash is being simulated. A store that threw it is treated as gone: reopen it, do not reuse it. */
export class EpcisStorageFault extends Error {
  readonly call: number;
  readonly when: 'before' | 'after';
  readonly method: string;
  constructor(call: number, when: 'before' | 'after', method: string) {
    super(`simulated crash ${when} durable call ${call} (${method})`);
    this.name = 'EpcisStorageFault';
    this.call = call;
    this.when = when;
    this.method = method;
  }
}

export interface EpcisStorageFaultPlan {
  /** The durable call to stop at, counted from 1 over putBytes, deleteBytes and commit. Omit it to count calls without stopping. */
  at?: number;
  /** `before`: the call never reaches the store. `after`: the call is durable and its answer is lost. */
  when?: 'before' | 'after';
}

export interface FaultInjectingEpcisStorage {
  storage: EpcisExchangeStorage;
  /** How many durable calls have been made so far, and which. */
  calls(): string[];
}

/**
 * Wrap a store so that it stops at a chosen durable call, the way a process
 * that died there would. After the fault every further call fails too, since
 * a dead process makes none. Used by the adapter suite and by any test that
 * needs a crash at a named step.
 */
export function faultInjectingEpcisStorage(inner: EpcisExchangeStorage, plan: EpcisStorageFaultPlan = {}): FaultInjectingEpcisStorage {
  const made: string[] = [];
  let dead: EpcisStorageFault | undefined;
  const alive = (): void => { if (dead != null) throw dead; };
  const durable = async <T>(method: string, run: () => Promise<T>): Promise<T> => {
    alive();
    made.push(method);
    const call = made.length;
    if (plan.at === call && (plan.when ?? 'before') === 'before') { dead = new EpcisStorageFault(call, 'before', method); throw dead; }
    const answer = await run();
    if (plan.at === call && plan.when === 'after') { dead = new EpcisStorageFault(call, 'after', method); throw dead; }
    return answer;
  };
  return {
    calls: () => [...made],
    storage: {
      putBytes: (sha256, bytes) => durable('putBytes', () => inner.putBytes(sha256, bytes)),
      deleteBytes: (sha256) => durable('deleteBytes', () => inner.deleteBytes(sha256)),
      commit: (writes) => durable('commit', () => inner.commit(writes)),
      getBytes: async (sha256) => { alive(); return inner.getBytes(sha256); },
      get: async (kind, key) => { alive(); return inner.get(kind, key); },
      list: async (kind, options) => { alive(); return inner.list(kind, options); },
    },
  };
}
